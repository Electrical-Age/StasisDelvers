package org.erisia.stasis;

import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.util.valueproviders.UniformInt;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.DropExperienceBlock;
import net.minecraft.world.level.block.RedStoneOreBlock;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.properties.BlockStateProperties;
import net.minecraft.world.level.material.MapColor;
import net.neoforged.neoforge.registries.DeferredBlock;

/**
 * Riftstone ores (λ-Nero: ore in rifts should look like ore in riftstone, not stone ore set into riftstone). One block
 * per ore material the rift scatter can place (RiftOreTable, generated by tools/ores/gen_riftstone_ores.py with its
 * textures, loot tables, tags and recipes). Each stands in for both its stone and deepslate source: it drops what the
 * stone source drops (its loot table runs the source's; silk touch gives the riftstone ore itself), carries the
 * sources' ore tags (so smelting by tag, EA's macerator, AE2 and the like treat it as that ore) plus
 * c:ores_in_ground/riftstone, and has the stone source's hardness (3/3) and XP.
 */
public final class RiftOres {
    private RiftOres() {
    }

    /** Variant per RiftOreTable entry, in table order. */
    public static final java.util.List<DeferredBlock<Block>> BLOCKS = new java.util.ArrayList<>();
    /** Variant block id -> its table entry (for tests). */
    static final java.util.Map<String, RiftOreTable.Entry> ENTRIES = new java.util.HashMap<>();

    static void register() {
        for (RiftOreTable.Entry e : RiftOreTable.ENTRIES) {
            DeferredBlock<Block> b = StasisRegistry.BLOCKS.registerBlock(e.name(),
                p -> e.redstone() ? new RedStoneOreBlock(p) : new DropExperienceBlock(UniformInt.of(e.xpMin(), e.xpMax()), p),
                p -> {
                    p = p.mapColor(MapColor.COLOR_PURPLE).strength(3f, 3f).requiresCorrectToolForDrops().sound(SoundType.DEEPSLATE);
                    // redstone: vanilla's lit glow on touch (RedStoneOreBlock needs its random ticks to go dark again)
                    return e.redstone() ? p.randomTicks().lightLevel(st -> st.getValue(BlockStateProperties.LIT) ? 9 : 0) : p;
                });
            StasisRegistry.ITEMS.registerSimpleBlockItem(b);
            BLOCKS.add(b);
            ENTRIES.put(StasisDelvers.MODID + ":" + e.name(), e);
        }
    }

    private static volatile java.util.Map<Block, BlockState> bySource;

    /** The riftstone ore that stands in for this stone or deepslate ore, or null if it has none (an ore the table
     * doesn't know: the scatter then places the source ore itself, as before). Safe off the main thread: built once
     * from the frozen block registry. */
    public static BlockState variantOf(Block source) {
        java.util.Map<Block, BlockState> m = bySource;
        if (m == null) {
            java.util.Map<Block, BlockState> n = new java.util.IdentityHashMap<>();
            for (int i = 0; i < BLOCKS.size(); i++) {
                RiftOreTable.Entry e = RiftOreTable.ENTRIES.get(i);
                BlockState v = BLOCKS.get(i).get().defaultBlockState();
                for (String id : new String[] {e.stoneSource(), e.deepslateSource()})
                    if (!id.isEmpty()) BuiltInRegistries.BLOCK.getOptional(Identifier.parse(id)).ifPresent(s -> n.put(s, v));
            }
            bySource = m = n;
        }
        return m.get(source);
    }

    /** The stone source of a variant ("" if the pack has none), for tests. */
    public static String stoneSource(Block variant) {
        RiftOreTable.Entry e = ENTRIES.get(BuiltInRegistries.BLOCK.getKey(variant).toString());
        return e == null ? null : e.stoneSource();
    }
}
